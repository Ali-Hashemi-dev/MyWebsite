import { existsSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { cleanArabicLine, normalizeArabicText, withBasePath } from "./article-renderer.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contentDir = path.join(root, "content", "articles");
const legacyHtmlDir = path.join(root, "public", "articles");
const generatedDataPath = path.join(root, "src", "data", "articles.generated.ts");

// Only the fields the site cannot invent are required; the rest default
// below so a minimal article published from the admin studio can never
// break the deploy. pdf stays optional (the reader hides the PDF link).
const requiredFields = ["id", "file", "title", "date", "genre"];

function parseScalar(value) {
  const trimmed = value.trim();

  if (trimmed.startsWith("[") && trimmed.endsWith("]")) {
    return trimmed
      .slice(1, -1)
      .split(",")
      .map((item) => item.trim().replace(/^["']|["']$/g, ""))
      .filter(Boolean);
  }

  return trimmed.replace(/^["']|["']$/g, "");
}

function parseFrontmatter(source, filePath) {
  const normalized = normalizeArabicText(source);
  const match = normalized.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);

  if (!match) {
    throw new Error(`Missing frontmatter in ${filePath}`);
  }

  const data = {};

  for (const line of match[1].split("\n")) {
    if (!line.trim() || line.trim().startsWith("#")) {
      continue;
    }

    const separator = line.indexOf(":");
    if (separator === -1) {
      throw new Error(`Invalid frontmatter line in ${filePath}: ${line}`);
    }

    const key = line.slice(0, separator).trim();
    const value = line.slice(separator + 1);
    data[key] = parseScalar(value);
  }

  for (const field of requiredFields) {
    if (data[field] === undefined || data[field] === "") {
      throw new Error(`Missing "${field}" in ${filePath}`);
    }
  }

  const defaults = {
    subtitle: "",
    year: (String(data.date).match(/\d{4}/) || [""])[0],
    category: "مزيج أدبي",
    themes: [],
    readingTime: "",
    words: "",
    mood: "",
    pdf: "",
    summary: "",
    signal: ""
  };
  for (const [field, value] of Object.entries(defaults)) {
    if (data[field] === undefined || data[field] === "") {
      data[field] = value;
    }
  }

  return {
    article: {
      ...data,
      // href feeds Next <Link>, which prepends basePath itself; pdf is a plain
      // <a> to a public/ asset, so it needs the prefix baked in.
      href: `/read/${data.file}/`,
      pdf: data.pdf ? withBasePath(data.pdf) : "",
      source: path.relative(root, filePath)
    },
    markdown: match[2].trim()
  };
}

function poemBlock(block) {
  const lines = block
    .replace(/^::poem\s*\n/, "")
    .replace(/\n::\s*$/, "")
    .split("\n")
    .map(cleanArabicLine)
    .filter(Boolean);

  return { type: "poem", lines };
}

function markdownBlockToBlock(block) {
  const trimmed = block.trim();
  const lines = trimmed.split("\n");

  if (!trimmed || trimmed.startsWith("<!--")) {
    return null;
  }

  if (trimmed.startsWith("::poem") && trimmed.endsWith("::")) {
    return poemBlock(trimmed);
  }

  if (lines.length === 1 && lines[0].startsWith("### ")) {
    return { type: "h3", text: cleanArabicLine(lines[0].slice(4)) };
  }

  if (lines.length === 1 && lines[0].startsWith("## ")) {
    return { type: "h2", text: cleanArabicLine(lines[0].slice(3)) };
  }

  if (lines.every((line) => line.trim().startsWith(">"))) {
    const quoteLines = lines.map((line) => cleanArabicLine(line.replace(/^>\s?/, ""))).filter(Boolean);
    return { type: "quote", lines: quoteLines };
  }

  return { type: "p", text: cleanArabicLine(lines.map(cleanArabicLine).join(" ")) };
}

function markdownToBlocks(markdown) {
  return normalizeArabicText(markdown)
    .split(/\n{2,}/)
    .map(markdownBlockToBlock)
    .filter(Boolean);
}

function sortArticles(left, right) {
  return left.id.localeCompare(right.id, "en", { numeric: true });
}

function toGeneratedArticle(article, body) {
  const {
    id,
    file,
    title,
    subtitle,
    date,
    year,
    category,
    genre,
    themes,
    readingTime,
    words,
    mood,
    href,
    pdf,
    summary,
    signal
  } = article;

  return {
    id,
    file,
    title,
    subtitle,
    date,
    year,
    category,
    genre,
    themes,
    readingTime,
    words,
    mood,
    href,
    pdf,
    summary,
    signal,
    body
  };
}

function writeGeneratedData(entries) {
  const generated = entries.map((entry) => toGeneratedArticle(entry.article, entry.body));
  const source = `// Generated by scripts/build-articles.mjs — do not edit by hand.
import type { Article } from "./articles";

export const articles = ${JSON.stringify(generated, null, 2)} satisfies Article[];
`;

  writeFileSync(generatedDataPath, source);
}

if (!existsSync(contentDir)) {
  throw new Error(`Missing content directory: ${contentDir}`);
}

const files = readdirSync(contentDir)
  .filter((file) => file.endsWith(".md"))
  .sort();

if (files.length === 0) {
  throw new Error(`No Markdown articles found in ${contentDir}`);
}

const entries = files
  .map((file) => {
    const filePath = path.join(contentDir, file);
    const parsed = parseFrontmatter(readFileSync(filePath, "utf8"), filePath);
    return {
      ...parsed,
      body: markdownToBlocks(parsed.markdown)
    };
  })
  .sort((left, right) => sortArticles(left.article, right.article));

// The reading experience now lives inside the app; drop the legacy static HTML output.
if (existsSync(legacyHtmlDir)) {
  rmSync(legacyHtmlDir, { recursive: true });
  console.log("removed legacy public/articles output");
}

writeGeneratedData(entries);
console.log(`generated src/data/articles.generated.ts (${entries.length} articles with body blocks)`);
